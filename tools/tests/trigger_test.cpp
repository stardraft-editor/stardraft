        for (const auto& p : d.params) {
            if (p.type.rfind("ValueOf:", 0) == 0) {  // follows another value (a property): that one must exist
                if (d.param(p.type.substr(8)) < 0) unknownTypes.insert(d.id + ":" + p.type);
            } else if (!triggerType(p.type)) unknownTypes.insert(p.type);
            else if (!triggerTypeClear(p.type)) ++unclear;
            if (d.sentence.find("{" + p.name + "}") == std::string::npos) unknownTypes.insert(d.id + ":" + p.name + " not in its sentence");
        }
