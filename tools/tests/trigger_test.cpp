        const fs::path lock = fs::path(STARDRAFT_SOURCE_DIR) / "research" / "data" / "trigger_schema.lock.txt";
        const std::set<std::string> now = schemaFacts();
        std::set<std::string> locked;
        {
            std::istringstream in(readText(lock));
            for (std::string line; std::getline(in, line);) {
                if (!line.empty() && line.back() == '\r') line.pop_back();  // a checkout with CR LF line ends
                if (!line.empty() && line[0] != '#') locked.insert(line);
            }
        }
        std::vector<std::string> gone, added;
        for (const auto& l : locked)
            if (!now.count(l) && l.rfind("format ", 0) != 0) gone.push_back(l);
        for (const auto& l : now)
            if (!locked.count(l)) added.push_back(l);
        for (const auto& g : gone) std::printf("      no longer there: %s\n", g.c_str());
        for (size_t i = 0; i < added.size() && i < 10; ++i) std::printf("      not in the lock yet: %s\n", added[i].c_str());
