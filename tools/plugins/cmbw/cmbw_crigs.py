#!/usr/bin/env python3
"""Makes src/mods/cmbw_crigs.inc: the Cosmonarchy BW trigger comment commands (CRIGs) and their arguments, for the
classic triggers' CRIG editor.

The mod's plugin reads each trigger's Comment as script lines; its commands and their argument types are the table in
Cosmonarchy-GPTP's systems/triggers/triggers.cpp (https://gitlab.com/the-no-frauds-club/tools/Cosmonarchy-GPTP).
This script reads that table:  .add_condition("kills", [](Area area, PlayerBitset source_players, ...) ...

usage: python tools/plugins/cmbw/cmbw_crigs.py <Cosmonarchy-GPTP checkout>
"""
import os
import re
import sys

# The plugin's argument types as the editor's kinds.
KINDS = {
    'Area': 'area', 'Location*': 'area',
    'PlayerBitset': 'players', 'PlayablePlayer': 'player', 'PlayerOrNeutral': 'player',
    'UnitIdBitset': 'units', 'UnitId::Enum': 'unit',
    'Quota': 'quota', 'TimeQuota': 'timequota', 'VarQuota': 'quota', 'TimerQuota': 'quota', 'EqualityQuota': 'equality',
    'Ticks': 'time', 'Seconds': 'seconds',
    's32': 'number', 'u32': 'number', 'int': 'number', 'f32': 'decimal', 'fp64': 'decimal', 'b32': 'bool', 'bool': 'bool',
    'std::string_view': 'text', 'std::string': 'text', 'Identifier': 'name',
    'v2u16': 'position',
}


def params_of(sig):
    out, depth, cur = [], 0, ''
    for ch in sig:
        if ch in '<(':
            depth += 1
        elif ch in '>)':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur.strip())
            cur = ''
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def main():
    src = open(os.path.join(sys.argv[1], 'systems', 'triggers', 'triggers.cpp'), encoding='utf-8').read()
    rows = []
    for m in re.finditer(r'\.add_(condition|local_action|action|flag)\(\s*(aliases\(([^)]*)\)|"([^"]+)")\s*,\s*\[\]\s*\(([^)]*)\)', src):
        kind, names = m.group(1), ([n.strip().strip('"') for n in m.group(3).split(',')] if m.group(3) else [m.group(4)])
        free = False
        args = []
        for p in params_of(m.group(5)):
            if not p:
                continue
            t, _, name = p.rpartition(' ')
            t = t.strip()
            if t == 'Context&':
                free = True  # (the command reads more of its line itself)
                continue
            opt = t.startswith('std::optional<')
            if opt:
                t = t[len('std::optional<'):-1]
            if t == 'Designator':
                pre = '' if name in ('designator',) else name.replace('designator_', '') + ' '
                args += [('area', pre + 'area', opt), ('players', pre + 'players', opt), ('units', pre + 'unit_ids', opt)]
                continue
            k = KINDS.get(t, 'word')  # (an enum or a set the plugin names: typed as a word)
            if t.startswith('Any<'):
                k = 'word'
            args.append((k, name, opt))
        rows.append((kind, '|'.join(names), args, free))
    out = os.path.join(os.path.dirname(__file__), '..', '..', '..', 'src', 'mods', 'cmbw_crigs.inc')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by tools/plugins/cmbw/cmbw_crigs.py from Cosmonarchy-GPTP systems/triggers/triggers.cpp (do not edit by hand).\n')
        f.write('// kind (condition, action, local action), names ("|" between aliases), arguments ("kind name", "?" optional), reads more\n')
        for kind, names, args, free in rows:
            a = ','.join(k + ('?' if o else '') + ' ' + n for k, n, o in args)
            f.write('{"%s", "%s", "%s", %s},\n' % (kind, names, a, 'true' if free else 'false'))
    print('wrote', os.path.normpath(out), len(rows), 'commands')


if __name__ == '__main__':
    main()
