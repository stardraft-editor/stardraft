"""Generates what libvpx's configure would, for a plain C build of its VP8 and VP9 decoders (no assembly, no
threads), so CMake can build it with any compiler: third_party/libvpx/ (vpx_config.h, vpx_version.h, the rtcd
headers) and third_party/libvpx/sources.cmake (the decoder's sources, from libvpx's own .mk files).

usage: python tools/gen_libvpx.py <libvpx source dir>   (libvpx 1.14.1, as CMakeLists.txt fetches it)
"""
import os
import re
import subprocess
import sys

SRC = sys.argv[1]
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'third_party', 'libvpx')
os.makedirs(OUT, exist_ok=True)

conf = open(os.path.join(SRC, 'configure'), encoding='utf-8').read()


def lst(name):
    body = re.search(r'^%s="(.*?)"' % name, conf, re.S | re.M).group(1)
    out = []
    for w in body.split():
        if w.startswith('${'):
            out += lst(w[2:-1])
        else:
            out.append(w)
    return out


ARCH = lst('ARCH_LIST')
HAVE = lst('HAVE_LIST')
CONFIG = lst('CONFIG_LIST')
YES = {'vp8', 'vp9', 'vp8_decoder', 'vp9_decoder', 'decoders', 'static', 'os_support', 'msvs', 'install_libs'}

h = ['/* Generated by tools/gen_libvpx.py: libvpx configured for a plain C build of the VP8 and VP9 decoders. */',
     '#ifndef VPX_CONFIG_H', '#define VPX_CONFIG_H', '#define RESTRICT', '#define INLINE __inline']
for prefix, names in (('VPX_ARCH', ARCH), ('HAVE', HAVE), ('CONFIG', CONFIG)):
    for n in names:
        h.append('#define %s_%s %d' % (prefix, n.upper(), 1 if (prefix == 'CONFIG' and n in YES) else 0))
h += ['#define DECODE_WIDTH_LIMIT 16384', '#define DECODE_HEIGHT_LIMIT 16384', '#endif /* VPX_CONFIG_H */', '']
open(os.path.join(OUT, 'vpx_config.h'), 'w', newline='\n').write('\n'.join(h))
open(os.path.join(OUT, 'vpx_config.c'), 'w', newline='\n').write(
    '#include "vpx/vpx_codec.h"\nstatic const char *const cfg = "--target=generic-gnu (StarDraft: C only, decoders)";\n'
    'const char *vpx_codec_build_config(void) { return cfg; }\n')
open(os.path.join(OUT, 'vpx_version.h'), 'w', newline='\n').write(
    '#define VERSION_MAJOR 1\n#define VERSION_MINOR 14\n#define VERSION_PATCH 1\n#define VERSION_EXTRA ""\n'
    '#define VERSION_PACKED ((VERSION_MAJOR << 16) | (VERSION_MINOR << 8) | (VERSION_PATCH))\n'
    '#define VERSION_STRING_NOSP "v1.14.1"\n#define VERSION_STRING " v1.14.1"\n')

# The rtcd headers: rtcd.pl with the configuration above, for the generic (C only) arch.
cfgfile = os.path.join(OUT, 'rtcd_config.txt')
with open(cfgfile, 'w', newline='\n') as f:
    for n in CONFIG:
        f.write('CONFIG_%s=%s\n' % (n.upper(), 'yes' if n in YES else ''))
for sym, defs, out in (('vp8_rtcd', 'vp8/common/rtcd_defs.pl', 'vp8_rtcd.h'), ('vp9_rtcd', 'vp9/common/vp9_rtcd_defs.pl', 'vp9_rtcd.h'),
                       ('vpx_dsp_rtcd', 'vpx_dsp/vpx_dsp_rtcd_defs.pl', 'vpx_dsp_rtcd.h'),
                       ('vpx_scale_rtcd', 'vpx_scale/vpx_scale_rtcd.pl', 'vpx_scale_rtcd.h')):
    text = subprocess.run(['perl', os.path.join(SRC, 'build/make/rtcd.pl'), '--arch=generic', '--sym=' + sym, '--config=' + cfgfile,
                           os.path.join(SRC, defs)], capture_output=True, text=True, check=True).stdout
    open(os.path.join(OUT, out), 'w', newline='\n').write(text)
os.remove(cfgfile)

# The sources: libvpx's .mk files, evaluated with the configuration (yes / empty).
VALUES = {('CONFIG_' + n.upper()): ('yes' if n in YES else '') for n in CONFIG}
VALUES.update({('HAVE_' + n.upper()): '' for n in HAVE})
VALUES.update({('VPX_ARCH_' + n.upper()): '' for n in ARCH})
VALUES['ARCH_X86'] = VALUES['ARCH_X86_64'] = ''


def subst(s):
    s = re.sub(r'\$\((\w+)\)', lambda m: VALUES.get(m.group(1), ''), s)
    # $(filter yes,a b c): "yes" when one of them is
    return re.sub(r'\$\(filter yes,([^)]*)\)', lambda m: 'yes' if 'yes' in m.group(1).split() else '', s)


def evaluate(mk, prefix, wanted):
    files, stack = [], []
    for raw in open(os.path.join(SRC, mk), encoding='utf-8'):
        line = raw.split('#', 1)[0].rstrip()
        if not line.strip():
            continue
        s = line.strip()
        m = re.match(r'(ifeq|ifneq)\s*\((.*)\)$', s)
        if m:
            a, b = (subst(m.group(2)).rsplit(',', 1) + [''])[:2]
            a, b = a.strip(), b.strip()
            stack.append((a == b) == (m.group(1) == 'ifeq'))
            continue
        if s == 'else':
            stack[-1] = not stack[-1]
            continue
        if s == 'endif':
            stack.pop()
            continue
        if not all(stack):
            continue
        m = re.match(r'(\w+)-(\S+)\s*\+=\s*(.*)', s)
        if m and m.group(1) in wanted and subst(m.group(2)) == 'yes':
            files += [prefix + f for f in m.group(3).split()]
    return files


srcs = []
for mk, prefix, wanted in (('vpx/vpx_codec.mk', 'vpx/', {'API_SRCS'}), ('vpx_mem/vpx_mem.mk', 'vpx_mem/', {'MEM_SRCS'}),
                           ('vpx_scale/vpx_scale.mk', 'vpx_scale/', {'SCALE_SRCS'}), ('vpx_ports/vpx_ports.mk', 'vpx_ports/', {'PORTS_SRCS'}),
                           ('vpx_dsp/vpx_dsp.mk', 'vpx_dsp/', {'DSP_SRCS'}), ('vpx_util/vpx_util.mk', 'vpx_util/', {'UTIL_SRCS'}),
                           ('vp8/vp8_common.mk', 'vp8/', {'VP8_COMMON_SRCS'}), ('vp8/vp8dx.mk', 'vp8/', {'VP8_DX_SRCS'}),
                           ('vp9/vp9_common.mk', 'vp9/', {'VP9_COMMON_SRCS'}), ('vp9/vp9dx.mk', 'vp9/', {'VP9_DX_SRCS'})):
    srcs += evaluate(mk, prefix, wanted)
srcs = sorted({s for s in srcs if s.endswith('.c')})
with open(os.path.join(OUT, 'sources.cmake'), 'w', newline='\n') as f:
    f.write('# Generated by tools/gen_libvpx.py: the C sources of libvpx\'s VP8 and VP9 decoders.\nset(VPX_SOURCES\n')
    for s in srcs:
        f.write('    ${libvpx_SOURCE_DIR}/%s\n' % s)
    f.write('    ${CMAKE_CURRENT_SOURCE_DIR}/third_party/libvpx/vpx_config.c)\n')
print(len(srcs), 'sources')
