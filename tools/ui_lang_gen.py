"""Make the translation tables of the editor (apps/editor/res/lang/*.cpp) from the translation files (*.tsv).

Usage: python -I tools/ui_lang_gen.py [--repo DIR]

Each translation file has one line per English UI text: ENGLISH<TAB>TRANSLATION. Both columns use backslash escapes:
\\ (a backslash), \\t (a tab: the shortcut part of a menu item), \\r and \\n. The English column is the key that
tr() looks up in apps/editor/ui_text.h, so it must be the exact text of the call site. Lines that are empty or start
with # are skipped. A translation that is equal to another English key is reported: tr() would translate it again.

The output is a C++ file per language: a table of {L"English", L"translation"}, with non-ASCII characters as \\uXXXX,
and the function that returns it (langTableKo, langTableEs, langTableRu or langTableZh, declared in apps/editor/ui_text.h).
"""
import argparse
import sys
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

LANGS = {"ko": "langTableKo", "es": "langTableEs", "ru": "langTableRu", "zh": "langTableZh"}


def unescape(s):
    out = []
    i = 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            n = s[i + 1]
            out.append({"t": "\t", "r": "\r", "n": "\n", "\\": "\\"}.get(n, "\\" + n))
            i += 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def cpp_literal(s):
    parts = []
    for ch in s:
        o = ord(ch)
        if ch == "\\":
            parts.append("\\\\")
        elif ch == '"':
            parts.append('\\"')
        elif ch == "\t":
            parts.append("\\t")
        elif ch == "\r":
            parts.append("\\r")
        elif ch == "\n":
            parts.append("\\n")
        elif 32 <= o < 127:
            parts.append(ch)
        elif o <= 0xFFFF:
            parts.append("\\u%04X" % o)
        else:
            raise ValueError("character outside the BMP: %r" % ch)
    return 'L"' + "".join(parts) + '"'


def read_table(path):
    rows = []
    for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip() or line.startswith("#"):
            continue
        if "\t" not in line:
            raise SystemExit("%s:%d: no tab between the English and the translation" % (path, n))
        en, tr = line.split("\t", 1)
        rows.append((unescape(en), unescape(tr)))
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", default=str(Path(__file__).resolve().parent.parent))
    args = ap.parse_args()
    lang_dir = Path(args.repo) / "apps" / "editor" / "res" / "lang"
    keys = set()
    tables = {}
    for code, name in LANGS.items():
        rows = read_table(lang_dir / (code + ".tsv"))
        tables[code] = rows
        for en, _ in rows:
            keys.add(en)
    for code, name in LANGS.items():
        rows = tables[code]
        seen = set()
        out = ["// Generated by tools/ui_lang_gen.py from res/lang/%s.tsv. Do not edit: change the .tsv and run the tool." % code,
               '#include "../../ui_lang.h"',
               "namespace {",
               "constexpr UiText kRows[] = {"]
        for en, tr in rows:
            if en in seen:
                raise SystemExit("%s: the English text is there twice: %r" % (code, en))
            seen.add(en)
            if tr in keys and tr != en:
                print("note: %s: the translation %r is also an English key (tr() would translate it again)" % (code, tr), file=sys.stderr)
            out.append("    {%s, %s}," % (cpp_literal(en), cpp_literal(tr)))
        if rows:
            out += ["};", "}  // namespace", "std::span<const UiText> %s() { return kRows; }" % name]
        else:  # no translations yet: an empty table (an array cannot have no element)
            out = out[:2] + ["std::span<const UiText> %s() { return {}; }" % name]
        (lang_dir / (code + ".cpp")).write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
        print("%s: %d texts" % (code, len(rows)))


if __name__ == "__main__":
    main()
